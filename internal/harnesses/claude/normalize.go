package claude

import (
	"encoding/json"
	"slices"
	"strconv"
	"strings"

	"github.com/MartinAndreev/conduit/internal/harnesses/claude/rules"
	"github.com/MartinAndreev/conduit/internal/harnesses/internal/boundedtext"
	"github.com/MartinAndreev/conduit/internal/lockscope"
	"github.com/MartinAndreev/conduit/internal/sessions/provider"
)

const (
	// maxNativeTextBytes bounds text copied from one native item into one event.
	maxNativeTextBytes = 64 * 1024
	// maxNativeErrorBytes bounds native error and notice text in one event.
	maxNativeErrorBytes = 4 * 1024
	// syntheticModel marks an assistant message generated by claude itself
	// (for example "Not logged in"), not by the model.
	syntheticModel = "<synthetic>"
)

// toolKind selects how a native tool is normalized. Tools absent from
// nativeTools are generic tool activity.
type toolKind int

const (
	toolGeneric toolKind = iota
	toolCommand
	toolFile
)

type toolDescriptor struct {
	kind      toolKind
	operation provider.FileOperation
}

// nativeTools is the single owner of the tool-name classification. Write may
// create or replace a file, which the native event does not distinguish.
var nativeTools = map[string]toolDescriptor{
	"Bash":         {kind: toolCommand},
	"Edit":         {kind: toolFile, operation: provider.FileUpdate},
	"MultiEdit":    {kind: toolFile, operation: provider.FileUpdate},
	"NotebookEdit": {kind: toolFile, operation: provider.FileUpdate},
	"Write":        {kind: toolFile, operation: provider.FileUnknown},
}

// Known native message types and system subtypes that carry no provider event.
var (
	ignoredMessageTypes   = []string{"rate_limit_event", "keep_alive", "tool_progress", "auth_status"}
	ignoredSystemSubtypes = []string{
		"thinking_tokens", "background_tasks_changed", "task_started", "task_updated",
		"task_progress", "task_notification", "compact_boundary", "hook_started",
		"hook_progress", "hook_response", "api_retry",
	}
)

type openTool struct {
	name       string
	descriptor toolDescriptor
	path       string
}

// normalizationState is owned by the transport reader goroutine: every native
// message is normalized there in wire order, so it needs no lock.
type normalizationState struct {
	textVersions  map[string]uint64
	textBytes     map[string]uint64
	blockCounts   map[string]int
	streamMessage string
	tools         map[string]openTool
}

func newNormalizationState() normalizationState {
	return normalizationState{
		textVersions: make(map[string]uint64),
		textBytes:    make(map[string]uint64),
		blockCounts:  make(map[string]int),
		tools:        make(map[string]openTool),
	}
}

// resetTurnItems drops per-message text and block state after a turn ends;
// message IDs do not recur, so this only bounds memory.
func (n *normalizationState) resetTurnItems() {
	clear(n.textVersions)
	clear(n.textBytes)
	clear(n.blockCounts)
	n.streamMessage = ""
}

// messageEnvelope holds the fields every stdout message may carry.
type messageEnvelope struct {
	Type            string  `json:"type"`
	Subtype         string  `json:"subtype"`
	SessionID       string  `json:"session_id"`
	UUID            string  `json:"uuid"`
	ParentToolUseID *string `json:"parent_tool_use_id"`
}

// handleMessage normalizes one stdout message on the reader goroutine.
func (s *session) handleMessage(messageType string, line []byte) {
	var envelope messageEnvelope
	if json.Unmarshal(line, &envelope) != nil {
		return
	}
	if envelope.SessionID != "" && envelope.SessionID != s.nativeSession {
		s.warnNativeOnce("session_mismatch", provider.ProtocolWarningEvent{
			Code: "session_mismatch", Detail: provider.BoundedText{Text: "native message referenced a different session ID"},
			OffendingNativeKind: messageType,
		})
	}
	switch messageType {
	case "system":
		s.normalizeSystem(envelope, line)
	case "command_lifecycle":
		s.normalizeCommandLifecycle(line)
	case "user":
		s.normalizeUser(envelope, line)
	case "assistant":
		s.normalizeAssistant(envelope, line)
	case "stream_event":
		s.normalizeStreamEvent(envelope, line)
	case "result":
		s.normalizeResult(line)
	default:
		if slices.Contains(ignoredMessageTypes, messageType) {
			return
		}
		s.warnUnknown(messageType)
	}
}

func (s *session) warnUnknown(kind string) {
	s.warnNativeOnce("unknown:"+kind, provider.ProtocolWarningEvent{
		Code: "unknown_native_message", Detail: provider.BoundedText{Text: "unsupported native message was not normalized"},
		OffendingNativeKind: boundedtext.String(kind, 128).Text,
	})
}

func (s *session) normalizeSystem(envelope messageEnvelope, line []byte) {
	switch envelope.Subtype {
	case "init":
		var message struct {
			Model string `json:"model"`
		}
		if json.Unmarshal(line, &message) == nil {
			s.observeModel(message.Model)
		}
	case "status":
		var message struct {
			Status *string `json:"status"`
		}
		if json.Unmarshal(line, &message) == nil && message.Status != nil && *message.Status != "" {
			s.observeStatus(*message.Status)
		}
	default:
		if slices.Contains(ignoredSystemSubtypes, envelope.Subtype) {
			return
		}
		s.warnUnknown("system/" + envelope.Subtype)
	}
}

// observeModel records the model of each system/init; a change between inits
// is reported, because usage and output then come from another model.
func (s *session) observeModel(model string) {
	if model == "" {
		return
	}
	var previous string
	_ = lockscope.WithMutexLock(&s.mu, func() error {
		previous = s.observedModel
		s.observedModel = model
		return nil
	})
	if previous != "" && previous != model {
		s.emit(provider.ProtocolWarningEvent{
			Code:                "model_changed",
			Detail:              boundedtext.String("native model changed from "+previous+" to "+model, maxNativeErrorBytes),
			OffendingNativeKind: "system/init",
		})
	}
}

// observeStatus maps system/status to a session observation. "idle" is never
// rewritten as a turn end; every other status means claude is working.
func (s *session) observeStatus(status string) {
	next := provider.SessionOpen
	if status == "idle" {
		next = provider.SessionIdleObserved
	}
	var previous provider.SessionState
	applied := false
	_ = lockscope.WithMutexLock(&s.mu, func() error {
		decision := rules.DecideStatusTransition(rules.StatusFacts{
			Closing: s.closing,
			Ended:   s.state == provider.SessionLost || s.state == provider.SessionClosed,
		})
		if decision.Kind != rules.StatusApply {
			return nil
		}
		previous = s.state
		s.state = next
		applied = true
		return nil
	})
	if applied {
		s.emit(provider.SessionStateEvent{Previous: previous, Current: next, NativeStatus: boundedtext.String(status, 128).Text})
	}
}

// normalizeCommandLifecycle treats `started` as delivery evidence. Other states
// (queued, cancelled, ...) are observations that never end a turn.
func (s *session) normalizeCommandLifecycle(line []byte) {
	var message struct {
		CommandUUID string `json:"command_uuid"`
		State       string `json:"state"`
	}
	if json.Unmarshal(line, &message) != nil {
		return
	}
	if message.State == "started" {
		s.observeDeliveryEvidence(message.CommandUUID)
	}
}

type nativeContentBlock struct {
	Type      string          `json:"type"`
	Text      string          `json:"text"`
	Thinking  string          `json:"thinking"`
	ID        string          `json:"id"`
	Name      string          `json:"name"`
	Input     json.RawMessage `json:"input"`
	ToolUseID string          `json:"tool_use_id"`
	Content   json.RawMessage `json:"content"`
	IsError   bool            `json:"is_error"`
}

func (s *session) normalizeUser(envelope messageEnvelope, line []byte) {
	var message struct {
		Message struct {
			Content json.RawMessage `json:"content"`
		} `json:"message"`
		IsReplay bool `json:"isReplay"`
		Origin   *struct {
			Kind string `json:"kind"`
		} `json:"origin"`
		ToolUseResult json.RawMessage `json:"tool_use_result"`
	}
	if json.Unmarshal(line, &message) != nil {
		return
	}
	if message.IsReplay {
		s.observeDeliveryEvidence(envelope.UUID)
		return
	}
	if message.Origin != nil && message.Origin.Kind == "task-notification" {
		s.emit(provider.ProtocolWarningEvent{
			Code: "native_wake", Detail: provider.BoundedText{Text: "a background task notification woke claude; no Conduit turn was started"},
			OffendingNativeKind: "user/task-notification",
		})
		return
	}
	if envelope.ParentToolUseID != nil {
		// Sub-agent tool results stay inside the parent tool item.
		return
	}
	var blocks []nativeContentBlock
	if json.Unmarshal(message.Message.Content, &blocks) != nil {
		return
	}
	for _, block := range blocks {
		if block.Type == "tool_result" {
			s.completeTool(block, message.ToolUseResult)
		}
	}
}

func (s *session) normalizeAssistant(envelope messageEnvelope, line []byte) {
	var message struct {
		Message struct {
			ID      string               `json:"id"`
			Model   string               `json:"model"`
			Content []nativeContentBlock `json:"content"`
		} `json:"message"`
	}
	if json.Unmarshal(line, &message) != nil {
		return
	}
	if envelope.ParentToolUseID != nil {
		s.normalizeSubagentAssistant(*envelope.ParentToolUseID, message.Message.Content)
		return
	}
	if message.Message.Model == syntheticModel {
		s.emit(provider.ProtocolWarningEvent{
			Code: "native_notice", Detail: boundedtext.String(joinedText(message.Message.Content), maxNativeErrorBytes),
			OffendingNativeKind: "assistant/" + syntheticModel,
		})
		return
	}
	// claude emits one assistant message per completed content block, all
	// sharing the message ID, in stream order; the running count is therefore
	// the block's stream index.
	messageID := message.Message.ID
	for _, block := range message.Message.Content {
		index := s.normalization.blockCounts[messageID]
		s.normalization.blockCounts[messageID] = index + 1
		item := textItemID(messageID, index)
		switch block.Type {
		case "text":
			s.emit(provider.AssistantTextEvent{Phase: provider.AssistantPhaseUnknown, Update: s.textSnapshot(item, "text", block.Text)})
		case "thinking":
			availability := provider.ReasoningUnavailable
			if block.Thinking != "" {
				availability = provider.ReasoningAvailable
			}
			s.emit(provider.ReasoningSummaryEvent{Availability: availability, Update: s.textSnapshot(item, "thinking", block.Thinking)})
		case "tool_use":
			s.startTool(block)
		default:
			s.warnUnknown("assistant/" + block.Type)
		}
	}
}

// normalizeSubagentAssistant attributes sub-agent output to the parent tool
// item. It never starts a separate turn or top-level item.
func (s *session) normalizeSubagentAssistant(parent string, blocks []nativeContentBlock) {
	var parts []string
	for _, block := range blocks {
		switch block.Type {
		case "text":
			parts = append(parts, block.Text)
		case "tool_use":
			parts = append(parts, "tool_use: "+block.Name)
		}
	}
	if len(parts) == 0 {
		return
	}
	s.emit(provider.ToolUpdatedEvent{
		ToolCallID: provider.NativeToolCallID(parent),
		Output:     boundedtext.String(strings.Join(parts, "\n"), maxNativeTextBytes),
		Mode:       provider.UpdateDelta,
	})
}

func (s *session) normalizeStreamEvent(envelope messageEnvelope, line []byte) {
	if envelope.ParentToolUseID != nil {
		return
	}
	var message struct {
		Event struct {
			Type    string `json:"type"`
			Index   int    `json:"index"`
			Message struct {
				ID string `json:"id"`
			} `json:"message"`
			Delta struct {
				Type     string `json:"type"`
				Text     string `json:"text"`
				Thinking string `json:"thinking"`
			} `json:"delta"`
		} `json:"event"`
	}
	if json.Unmarshal(line, &message) != nil {
		return
	}
	event := message.Event
	switch event.Type {
	case "message_start":
		s.normalization.streamMessage = event.Message.ID
	case "content_block_delta":
		if event.Delta.Type != "text_delta" && event.Delta.Type != "thinking_delta" {
			return
		}
		if s.normalization.streamMessage == "" {
			s.warnNativeOnce("stream_event:uncorrelated", provider.ProtocolWarningEvent{
				Code: "uncorrelated_text_delta", Detail: provider.BoundedText{Text: "ignored a delta without a preceding message_start"},
				OffendingNativeKind: "stream_event/content_block_delta",
			})
			return
		}
		item := textItemID(s.normalization.streamMessage, event.Index)
		if event.Delta.Type == "text_delta" {
			s.emit(provider.AssistantTextEvent{Phase: provider.AssistantPhaseUnknown, Update: s.textDelta(item, "text", event.Delta.Text)})
			return
		}
		s.emit(provider.ReasoningSummaryEvent{Availability: provider.ReasoningAvailable, Update: s.textDelta(item, "thinking", event.Delta.Thinking)})
	}
}

func textItemID(messageID string, index int) string {
	return messageID + "#" + strconv.Itoa(index)
}

func joinedText(blocks []nativeContentBlock) string {
	var parts []string
	for _, block := range blocks {
		if block.Type == "text" {
			parts = append(parts, block.Text)
		}
	}
	return strings.Join(parts, "\n")
}

func (s *session) startTool(block nativeContentBlock) {
	descriptor := nativeTools[block.Name]
	var input map[string]json.RawMessage
	_ = json.Unmarshal(block.Input, &input)
	tool := openTool{name: block.Name, descriptor: descriptor}
	switch descriptor.kind {
	case toolCommand:
		var command string
		_ = json.Unmarshal(input["command"], &command)
		s.normalization.tools[block.ID] = tool
		s.emit(provider.CommandStartedEvent{
			CommandID: provider.NativeCommandID(block.ID),
			Display:   boundedtext.String(command, maxNativeTextBytes), CWD: s.workspace,
		})
		return
	case toolFile:
		tool.path = toolFilePath(input)
	}
	s.normalization.tools[block.ID] = tool
	s.emit(provider.ToolStartedEvent{
		ToolCallID: provider.NativeToolCallID(block.ID), ToolName: block.Name,
		Arguments: boundedtext.Bytes(block.Input, maxNativeTextBytes),
	})
}

// toolFilePath reads `file_path`, then `notebook_path`.
func toolFilePath(input map[string]json.RawMessage) string {
	for _, key := range []string{"file_path", "notebook_path"} {
		var path string
		if json.Unmarshal(input[key], &path) == nil && path != "" {
			return path
		}
	}
	return ""
}

func (s *session) completeTool(block nativeContentBlock, rawResult json.RawMessage) {
	tool, known := s.normalization.tools[block.ToolUseID]
	if !known {
		s.warnNativeOnce("tool_result:uncorrelated", provider.ProtocolWarningEvent{
			Code: "uncorrelated_tool_result", Detail: provider.BoundedText{Text: "ignored a tool result without a matching tool_use"},
			OffendingNativeKind: "user/tool_result",
		})
		return
	}
	delete(s.normalization.tools, block.ToolUseID)
	// tool_use_result is an object for Bash and may be a plain error string.
	var result struct {
		Interrupted bool `json:"interrupted"`
	}
	_ = json.Unmarshal(rawResult, &result)
	outcome := rules.DecideToolOutcome(rules.ToolOutcomeFacts{IsError: block.IsError, Interrupted: result.Interrupted})
	output := boundedtext.String(toolResultText(block.Content), maxNativeTextBytes)
	switch tool.descriptor.kind {
	case toolCommand:
		s.completeCommand(block.ToolUseID, outcome.Kind, output)
	default:
		s.emit(provider.ToolCompletedEvent{ToolCallID: provider.NativeToolCallID(block.ToolUseID), Outcome: toolOutcome(outcome.Kind), Output: output})
		if tool.descriptor.kind == toolFile {
			s.reportFileActivity(block.ToolUseID, tool, outcome.Kind)
		}
	}
}

// completeCommand reports a Bash result. The native tool_result carries no exit
// code; because CommandCompletedEvent has no outcome field, a failed or
// interrupted command is described by a warning before the completion.
func (s *session) completeCommand(toolUseID string, outcome rules.ToolOutcomeKind, output provider.BoundedText) {
	switch outcome {
	case rules.ToolOutcomeFailed:
		s.emit(provider.ProtocolWarningEvent{Code: "command_failed", Detail: provider.BoundedText{Text: "native command failed without an exit code"}, OffendingNativeKind: "user/tool_result"})
	case rules.ToolOutcomeCancelled:
		s.emit(provider.ProtocolWarningEvent{Code: "command_interrupted", Detail: provider.BoundedText{Text: "native command was interrupted"}, OffendingNativeKind: "user/tool_result"})
	}
	s.emit(provider.CommandCompletedEvent{CommandID: provider.NativeCommandID(toolUseID), ExitCode: provider.None[int](), Output: output})
}

// reportFileActivity reports only a successful file tool; a failed edit was not
// applied and carries no path.
func (s *session) reportFileActivity(toolUseID string, tool openTool, outcome rules.ToolOutcomeKind) {
	if outcome != rules.ToolOutcomeSucceeded {
		s.emit(provider.ProtocolWarningEvent{
			Code: "file_change_not_applied", Detail: boundedtext.String("native "+tool.name+" did not succeed", 256),
			OffendingNativeKind: "user/tool_result",
		})
		return
	}
	s.emit(provider.FileActivityEvent{
		Operation: tool.descriptor.operation, NativePath: tool.path,
		ToolCallID: provider.Some(provider.NativeToolCallID(toolUseID)),
	})
}

// toolResultText reads tool_result content: a string or an array of blocks of
// which only text blocks are kept.
func toolResultText(raw json.RawMessage) string {
	var text string
	if json.Unmarshal(raw, &text) == nil {
		return text
	}
	var blocks []nativeContentBlock
	if json.Unmarshal(raw, &blocks) == nil {
		return joinedText(blocks)
	}
	return ""
}

func toolOutcome(kind rules.ToolOutcomeKind) provider.ToolOutcome {
	switch kind {
	case rules.ToolOutcomeSucceeded:
		return provider.ToolSucceeded
	case rules.ToolOutcomeFailed:
		return provider.ToolFailed
	case rules.ToolOutcomeCancelled:
		return provider.ToolCancelled
	}
	return provider.ToolUnknown
}

// textSnapshot replaces one segment version. The byte offset of later deltas
// continues from the snapshot's original length.
func (s *session) textSnapshot(item, segment, text string) provider.TextSegmentUpdate {
	bounded := boundedtext.String(text, maxNativeTextBytes)
	key := item + "\x00" + segment
	version := s.normalization.textVersions[key] + 1
	s.normalization.textVersions[key] = version
	s.normalization.textBytes[key] = bounded.OriginalBytes.Value
	return provider.TextSegmentUpdate{
		ItemID: provider.ItemID(item), SegmentID: provider.SegmentID(segment), Text: bounded.Text,
		Mode: provider.UpdateSnapshot, BaseVersion: provider.None[uint64](), Version: version,
		Truncated: bounded.Truncated, OriginalBytes: bounded.OriginalBytes,
	}
}

// textDelta applies to the previous version at the original byte offset.
func (s *session) textDelta(item, segment, text string) provider.TextSegmentUpdate {
	bounded := boundedtext.String(text, maxNativeTextBytes)
	key := item + "\x00" + segment
	base := s.normalization.textVersions[key]
	offset := s.normalization.textBytes[key]
	version := base + 1
	s.normalization.textVersions[key] = version
	s.normalization.textBytes[key] = offset + bounded.OriginalBytes.Value
	return provider.TextSegmentUpdate{
		ItemID: provider.ItemID(item), SegmentID: provider.SegmentID(segment), Text: bounded.Text,
		Mode: provider.UpdateDelta, BaseVersion: provider.Some(base), Version: version,
		ByteOffset: offset, Truncated: bounded.Truncated, OriginalBytes: bounded.OriginalBytes,
	}
}
